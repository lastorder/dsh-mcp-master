/**
 * Build both halves of the plugin:
 * - `src/index.ts`         → `lib/index.js`  (Host half, ESM, imported by the Loader row)
 * - `src/client/index.tsx` → `lib/client.js` (Client half: a classic script calling
 *   `window.__ModuleLoader__.load({ id, factory })`; React arrives through the
 *   factory's `require`, so it is never bundled)
 *
 * Usage: `node scripts/build.mjs`
 */
import { build } from 'esbuild'
import { readFileSync, rmSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const manifest = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))

/** Module specifiers the DSH browser module table provides to every Client half. */
const CLIENT_EXTERNALS = ['react', 'react/jsx-runtime', 'react-dom']

rmSync(join(root, 'lib'), { recursive: true, force: true })

await build({
  entryPoints: [join(root, 'src/index.ts')],
  outfile: join(root, 'lib/index.js'),
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  legalComments: 'none',
  define: { __PLUGIN_VERSION__: JSON.stringify(manifest.version) },
  banner: { js: `// ${manifest.name} ${manifest.version} — generated by scripts/build.mjs; edit src/ instead.` },
})

await build({
  entryPoints: [join(root, 'src/client/index.tsx')],
  outfile: join(root, 'lib/client.js'),
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  external: CLIENT_EXTERNALS,
  legalComments: 'none',
  define: { __PLUGIN_VERSION__: JSON.stringify(manifest.version) },
  banner: {
    js: [
      `// ${manifest.name} ${manifest.version} — generated by scripts/build.mjs; edit src/client instead.`,
      'window.__ModuleLoader__.load({',
      `  id: ${JSON.stringify(manifest.name)},`,
      '  factory: (require) => {',
      '    var module = { exports: {} };',
      '    var exports = module.exports;',
    ].join('\n'),
  },
  footer: { js: '    return module.exports;\n  },\n});' },
})

console.log(`built ${manifest.name}@${manifest.version}: lib/index.js, lib/client.js`)
